package opencode

import (
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
	"time"

	"github.com/re-cinq/shift-log/internal/agent"
)

// GetDataDir returns the OpenCode data directory.
// OpenCode follows XDG conventions: it uses $XDG_DATA_HOME/opencode on Linux
// and ~/Library/Application Support/opencode on macOS.
func GetDataDir() (string, error) {
	if runtime.GOOS == "darwin" {
		home, err := os.UserHomeDir()
		if err != nil {
			return "", fmt.Errorf("could not determine home directory: %w", err)
		}
		return filepath.Join(home, "Library", "Application Support", "opencode"), nil
	}

	// Linux/other: respect XDG_DATA_HOME, default to ~/.local/share
	if xdg := os.Getenv("XDG_DATA_HOME"); xdg != "" {
		return filepath.Join(xdg, "opencode"), nil
	}

	home, err := os.UserHomeDir()
	if err != nil {
		return "", fmt.Errorf("could not determine home directory: %w", err)
	}
	return filepath.Join(home, ".local", "share", "opencode"), nil
}

// GetProjectID returns the project identifier for OpenCode.
// For git repos, this is the root commit hash. For non-git dirs, it's "global".
func GetProjectID(projectPath string) string {
	cmd := exec.Command("git", "rev-list", "--max-parents=0", "--all")
	cmd.Dir = projectPath
	output, err := cmd.Output()
	if err != nil {
		return "global"
	}

	// Take the first line (first root commit)
	lines := strings.Split(strings.TrimSpace(string(output)), "\n")
	if len(lines) > 0 && lines[0] != "" {
		return strings.TrimSpace(lines[0])
	}
	return "global"
}

// GetSessionDir returns the session storage directory for a project.
func GetSessionDir(projectPath string) (string, error) {
	dataDir, err := GetDataDir()
	if err != nil {
		return "", err
	}

	projectID := GetProjectID(projectPath)
	return filepath.Join(dataDir, "storage", "session", projectID), nil
}

// GetMessageDir returns the message storage directory for a session.
func GetMessageDir(sessionID string) (string, error) {
	dataDir, err := GetDataDir()
	if err != nil {
		return "", err
	}

	return filepath.Join(dataDir, "storage", "message", sessionID), nil
}

// sessionInfo represents an OpenCode session JSON file.
type sessionInfo struct {
	ID        string `json:"id"`
	ProjectID string `json:"projectID,omitempty"`
	Directory string `json:"directory,omitempty"`
	Title     string `json:"title,omitempty"`
}

// activeSessionFile represents the .shiftlog/active-session.json file written
// directly by the OpenCode plugin (via the SDK client) on every tool
// execution. This is checked before falling back to scanning OpenCode's
// internal storage, since that storage format has changed across OpenCode
// releases (flat JSON files in older versions, SQLite in others) while the
// plugin's client SDK API has remained stable.
type activeSessionFile struct {
	SessionID      string `json:"session_id"`
	ProjectPath    string `json:"project_path"`
	StartedAt      string `json:"started_at"`
	TranscriptData string `json:"transcript_data"`
}

// discoverFromActiveSession reads .shiftlog/active-session.json for a direct
// pointer to the active session and its transcript, as recorded by the
// OpenCode plugin. Returns nil (not an error) if the file is missing, stale,
// for a different project, or has no transcript data yet.
func discoverFromActiveSession(projectPath string) (*agent.SessionInfo, error) {
	sessionPath := filepath.Join(projectPath, ".shiftlog", "active-session.json")

	data, err := os.ReadFile(sessionPath)
	if err != nil {
		return nil, nil
	}

	var active activeSessionFile
	if err := json.Unmarshal(data, &active); err != nil {
		return nil, nil
	}

	if active.SessionID == "" || active.TranscriptData == "" {
		return nil, nil
	}

	if !agent.PathsEqual(active.ProjectPath, projectPath) {
		return nil, nil
	}

	info, err := os.Stat(sessionPath)
	if err != nil {
		return nil, nil
	}
	if time.Since(info.ModTime()) > agent.RecentSessionTimeout {
		return nil, nil
	}

	return &agent.SessionInfo{
		SessionID:      active.SessionID,
		StartedAt:      active.StartedAt,
		ProjectPath:    active.ProjectPath,
		TranscriptData: []byte(active.TranscriptData),
	}, nil
}

// WriteSessionFile writes a session and its messages to OpenCode's storage.
func WriteSessionFile(projectPath, sessionID string, transcriptData []byte) (string, error) {
	sessionDir, err := GetSessionDir(projectPath)
	if err != nil {
		return "", err
	}

	if err := os.MkdirAll(sessionDir, 0700); err != nil {
		return "", fmt.Errorf("could not create session directory: %w", err)
	}

	sessionPath := filepath.Join(sessionDir, sessionID+".json")

	// Write a minimal session file
	session := sessionInfo{
		ID:        sessionID,
		ProjectID: GetProjectID(projectPath),
		Directory: projectPath,
		Title:     "Restored session",
	}

	data, err := json.MarshalIndent(session, "", "  ")
	if err != nil {
		return "", fmt.Errorf("could not marshal session: %w", err)
	}

	if err := os.WriteFile(sessionPath, data, 0600); err != nil {
		return "", fmt.Errorf("could not write session file: %w", err)
	}

	// Write messages from transcript data
	msgDir, err := GetMessageDir(sessionID)
	if err != nil {
		return sessionPath, nil // Session created, messages optional
	}

	if err := os.MkdirAll(msgDir, 0700); err != nil {
		return sessionPath, nil
	}

	// Write the raw transcript data as a single message file for restore
	msgPath := filepath.Join(msgDir, "transcript.jsonl")
	_ = os.WriteFile(msgPath, transcriptData, 0600)

	return sessionPath, nil
}
